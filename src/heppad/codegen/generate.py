"""Turn a PlotSpec into a standalone matplotlib/mplhep script.

The script is built from segments (figure setup, one per layer, axes settings,
labels, legends, annotations). The exported script is their concatenation;
the editor executes the same segments one by one, so it can tag what each
segment drew with the spec path it came from and keep going when one fails.
"""

from __future__ import annotations

