# ------------------------------------------------------------------ code helpers


class Code(str):
    """A Python expression inserted verbatim (not quoted) by ``lit``."""


def lit(value) -> str:
    if isinstance(value, Code):
        return str(value)
    if isinstance(value, str):
        if "\\" in value and "'" not in value and not value.endswith("\\") and "\n" not in value:
            return f"r'{value}'"
        return repr(value)
    if isinstance(value, tuple):
        return "(" + ", ".join(lit(v) for v in value) + ("," if len(value) == 1 else "") + ")"
    if isinstance(value, list):
        return "[" + ", ".join(lit(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{lit(k)}: {lit(v)}" for k, v in value.items()) + "}"
    return repr(value)


def call(func: str, *args, **kwargs) -> str:
    """Format a call, dropping None-valued kwargs; wraps long calls one arg per line."""
    parts = [lit(a) for a in args] + [f"{k}={lit(v)}" for k, v in kwargs.items() if v is not None]
    one_line = f"{func}({', '.join(parts)})"
    if len(one_line) <= 88:
        return one_line
    return f"{func}(\n" + "".join(f"    {p},\n" for p in parts) + ")"


def ident(name: str) -> str:
    name = re.sub(r"\W", "_", name)
    return f"_{name}" if not name or name[0].isdigit() else name


# --------------------------------------------------------------------- program


@dataclass
class Segment:
    kind: str  # setup | layer | annotation | axes | label | legend
    code: str
    gid: str | None = None
    # Name of a variable holding one artist group per stack member.
    members: str | None = None
    what: str = ""  # for warnings, e.g. "layer 'data'"


@dataclass
class Program:
    imports: str
    inputs: dict[str, str]
    helpers: list[str]
    style: str
    segments: list[Segment] = field(default_factory=list)
    output: str = "plot.pdf"
    source_name: str | None = None
    dpi: float = 100

    def helper_source(self) -> str:
        return "\n\n".join(_helper_source(name) for name in self.helpers)

    def source(self) -> str:
        doc = '"""Plot generated by hep-pad'
        doc += f" from {self.source_name}." if self.source_name else "."
        doc += '\n\nRequires numpy, matplotlib, mplhep and uproot.\n"""\n'
        body = [
            doc,
            self.imports,
            "BASE = Path(__file__).resolve().parent",
            f"INPUTS = {lit(self.inputs)}",
            "",
            self.helper_source(),
            "",
            self.style,
        ]
        last_kind = None
        for seg in self.segments:
            if seg.kind != last_kind or seg.kind in ("layer", "label", "legend"):
                body.append("")
            body.append(seg.code)
            last_kind = seg.kind
        body += ["", f"fig.savefig(BASE / {lit(self.output)}, dpi={lit(self.dpi)})", ""]
        return "\n".join(body)


