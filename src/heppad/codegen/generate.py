def generate(
    spec: m.PlotSpec,
    base_dir: str | Path = ".",
    script_dir: str | Path | None = None,
    output: str = "plot.pdf",
    source_name: str | None = None,
) -> Program:
    """Build the program for ``spec``.

    Input paths are resolved against ``base_dir`` (the spec's directory). With
    ``script_dir`` they are written relative to where the script will live;
    otherwise they are absolute. URLs are kept as they are.
    """
    gen = _Generator(spec)
    gen.run()
    inputs = {}
    for key in gen.input_keys:
        if is_url(spec.inputs.get(key, key)):
            inputs[key] = spec.inputs.get(key, key)
            continue
        path = Path(spec.inputs.get(key, key)).expanduser()
        if not path.is_absolute():
            path = Path(base_dir).resolve() / path
        inputs[key] = os.path.relpath(path, Path(script_dir).resolve()) if script_dir else str(path)
    style = f"plt.style.use(hep.style.{spec.style})\n"
    style += '# Save the full canvas, never a tight crop (some styles set savefig.bbox = "tight").\n'
    style += 'plt.rcParams["savefig.bbox"] = "standard"'
    return Program(
        imports=IMPORTS,
        inputs=inputs,
        helpers=_with_dependencies(gen.helpers),
        style=style,
        segments=gen.segments,
        output=output,
        source_name=source_name,
        dpi=spec.canvas.dpi,
    )


def _with_dependencies(names: set[str]) -> list[str]:
    order = ["Hist1D", "Syst", "tree_columns", "read_tree", "read", "load", "hist1d", "add", "auto_yerr", "ratio", "pull",
             "hist2d", "object_paths", "systematics", "group_sources", "band_errors", "sort_legend"]
    needed, todo = set(), list(names)
    while todo:
        name = todo.pop()
        if name not in needed:
            needed.add(name)
            todo += runtime.DEPENDS.get(name, [])
    return [n for n in order if n in needed]


def _helper_source(name: str) -> str:
    if name == "Hist1D":
        return 'Hist1D = namedtuple("Hist1D", "edges values variances")'
    if name == "Syst":
        return 'Syst = namedtuple("Syst", "down up sources missing")'
    return inspect.getsource(getattr(runtime, name)).rstrip()


class _Generator:
    def __init__(self, spec: m.PlotSpec):
        self.spec = spec
        self.segments: list[Segment] = []
        self.helpers: set[str] = set()
        self.input_keys: list[str] = []
        self.ax = {p.id: ident(f"ax_{p.id}") for p in spec.pads}
        self.hvar = {layer.id: ident(f"h_{layer.id}") for p in spec.pads for layer in p.layers}
        # Histogram variables for which a ``<var>_syst`` has been computed.
        self.has_syst: set[str] = set()

    def run(self) -> None:
        self.setup()
        for pad in self.spec.pads:
            for layer in pad.layers:
                code, members = getattr(self, f"layer_{layer.kind}")(pad, layer)
                self.add("layer", code, f"pads.{pad.id}.layers.{layer.id}",
                         members=members, what=f"layer {layer.id!r}")
            for i, ann in enumerate(pad.annotations):
                self.add("annotation", self.annotation(pad, ann),
                         f"pads.{pad.id}.annotations.{i}", what=f"annotation {i} in pad {pad.id!r}")
        for pad in self.spec.pads:
            code = self.axes(pad)
            if code:
                self.add("axes", code, None, what=f"axes of pad {pad.id!r}")
        for pad in self.spec.pads:
            if pad.label is not None and pad.label.show:
                self.add("label", self.label(pad), f"pads.{pad.id}.label",
                         what=f"label of pad {pad.id!r}")
        for pad in self.spec.pads:
            if pad.legend.show:
                self.add("legend", self.legend(pad), f"pads.{pad.id}.legend",
                         what=f"legend of pad {pad.id!r}")

    def add(self, kind, code, gid, members=None, what=""):
        self.segments.append(Segment(kind, code, gid, members, what))

    def refs(self, ref: m.RefLike) -> Code:
        refs = ref if isinstance(ref, list) else [ref]
        for r in refs:
            if r.file not in self.input_keys:
                self.input_keys.append(r.file)
        return Code(lit([(r.file, r.path) if r.expr is None else (r.file, r.path, r.tree())
                         for r in refs]))

    # -- setup

    def setup(self) -> None:
        from ..render.figure import effective_layout

        spec, lay = self.spec, self.spec.layout
        eff = effective_layout(spec)
        mg = eff["margins"]
        lines = [
            "fig = " + call("plt.figure", figsize=(spec.canvas.width, spec.canvas.height),
                            dpi=spec.canvas.dpi),
            "grid = " + call(
                "fig.add_gridspec", lay.rows, lay.cols,
                left=_r(mg["left"]), right=_r(1 - mg["right"]),
                top=_r(1 - mg["top"]), bottom=_r(mg["bottom"]),
                hspace=_r(eff["hspace"]), wspace=_r(eff["wspace"]),
                height_ratios=lay.height_ratios, width_ratios=lay.width_ratios,
            ),
        ]
        for p in spec.pads:
            cell = Code(f"grid[{_span(p.row, p.rowspan)}, {_span(p.col, p.colspan)}]")
            lines.append(f"{self.ax[p.id]} = {call('fig.add_subplot', cell)}")
        for p in spec.pads:
            if p.sharex is not None:
                lines.append(f"{self.ax[p.id]}.sharex({self.ax[_xroot(spec, p).id]})")
        self.add("setup", "\n".join(lines), None, what="figure setup")

    # -- layers

    def _hist1d(self, ref, ops: m.HistOps) -> str:
        self.helpers.add("hist1d")
        return call(
            "hist1d", self.refs(ref),
            flow="fold" if ops.flow == "fold" else None,
            rebin=ops.rebin,
            xrange=list(ops.xrange) if ops.xrange else None,
            scale=ops.scale if ops.scale != 1.0 else None,
            normalize=True if ops.normalize else None,
        )

    def _systematics(self, h: str, components, common, symmetrize) -> str:
        """``<h>_syst = systematics(...)`` for (ref, ops, systematics) components."""
        self.helpers.add("systematics")
        comps = []
        for ref, ops, systs in components:
            comp = {"refs": self.refs(ref)}
            opts = _ops_dict(ops)
            if opts:
                comp["ops"] = opts
            if systs:
                comp["syst"] = [_syst_dict(x) for x in systs]
            comps.append(comp)
        # Variations may live in another input file; it must be listed in INPUTS.
        for x in [*common, *(x for _, _, systs in components for x in systs)]:
            file = getattr(x, "file", None)
            if file is not None and file not in self.input_keys:
                self.input_keys.append(file)
        lines = [f"{h}_syst = systematics(", "    ["]
        for c in comps:
            if "syst" not in c and len(lit(c)) <= 76:
                lines.append(f"        {lit(c)},")
                continue
            lines.append("        {")
            lines += [f"            {lit(k)}: {lit(v)}," for k, v in c.items() if k != "syst"]
            if "syst" in c:
                lines.append("            'syst': [")
                lines += [f"                {lit(x)}," for x in c["syst"]]
                lines.append("            ],")
            lines.append("        },")
        lines.append("    ],")
        if common:
            lines.append("    common=[")
            lines += [f"        {lit(_syst_dict(x))}," for x in common]
            lines.append("    ],")
        if symmetrize != "none":
            lines.append(f"    symmetrize={lit(symmetrize)},")
        lines.append(")")
        self.has_syst.add(h)
        return "\n".join(lines)

    def _errors(self, layer_id: str, content, down: str, up: str) -> list[str]:
        """Lines assigning the absolute (down, up) errors of a histogram/stack layer."""
        h = self.hvar[layer_id]
        items = _content_items(content)
        stat = f"np.sqrt({h}.variances)"
        has_syst = h in self.has_syst
        groups = getattr(self.spec.layer(layer_id), "syst_groups", {})
        # Spell out the common cases; anything involving groups uses the helper.
        if items == ["stat"] or (not has_syst and items == ["stat", "syst"]):
            return [f"{down} = {up} = {stat}"]
        if not has_syst and items == ["syst"]:
            return [f"{down} = {up} = np.zeros_like({h}.values)  # no systematics defined"]
        if has_syst and items == ["syst"]:
            return [f"{down}, {up} = {h}_syst.down, {h}_syst.up"]
        if has_syst and items == ["stat", "syst"]:
            return [f"{down} = np.hypot({stat}, {h}_syst.down)",
                    f"{up} = np.hypot({stat}, {h}_syst.up)"]
        self.helpers.add("band_errors")
        return [f"{down}, {up} = " + call(
            "band_errors", Code(h), Code(f"{h}_syst" if has_syst else "None"), items,
            groups=groups or None)]

    def layer_histogram(self, pad, layer: m.HistogramLayer):
        h = self.hvar[layer.id]
        lines = [f"# {layer.id}: histogram", f"{h} = {self._hist1d(layer.ref, layer)}"]
        if layer.systematics:
            lines.append(self._systematics(h, [(layer.ref, layer, layer.systematics)], [],
                                           layer.symmetrize))
        if layer.visible:
            errbar = layer.histtype == "errorbar"
            mode = layer.yerr
            if mode == "auto":
                self.helpers.add("auto_yerr")
                yerr = Code(f"auto_yerr({h})") if errbar else False
            else:
                yerr = {"none": False, "poisson": True,
                        "sumw2": Code(f"np.sqrt({h}.variances)")}[mode]
            lines.append(call(
                "hep.histplot", Code(f"{h}.values"), Code(f"{h}.edges"),
                ax=Code(self.ax[pad.id]), histtype=layer.histtype, yerr=yerr,
                xerr=True if layer.xerr else None, binwnorm=layer.binwnorm,
                label=layer.label, color=layer.color,
                linewidth=None if errbar else layer.linewidth,
                elinewidth=layer.linewidth if errbar else None,
                linestyle=layer.linestyle, alpha=layer.alpha, hatch=layer.hatch,
                marker=layer.marker if errbar else None,
                markersize=layer.markersize if errbar else None,
                zorder=layer.zorder, flow="none",
            ))
        return "\n".join(lines), None

    def layer_stack(self, pad, layer: m.StackLayer):
        h = self.hvar[layer.id]
        parts = f"{h}_parts"
        if not layer.members:
            return f"# {layer.id}: empty stack", None
        self.helpers.add("add")
        lines = [f"# {layer.id}: stack", f"{parts} = ["]
        for mb in layer.members:
            comment = f"  # {mb.label}" if mb.label else ""
            lines.append(_indent(self._hist1d(mb.ref, mb)) + "," + comment)
        lines += ["]", f"{h} = add({parts})"]
        if layer.systematics or any(mb.systematics for mb in layer.members):
            lines.append(self._systematics(
                h, [(mb.ref, mb, mb.systematics) for mb in layer.members],
                layer.systematics, layer.symmetrize))
        members = None
        if layer.visible:
            kwargs = {}
            for key in ("label", "color", "edgecolor", "hatch"):
                values = [getattr(mb, key) for mb in layer.members]
                if any(v is not None for v in values):
                    kwargs[key] = values
            members = ident(f"{layer.id}_artists")
            lines.append(f"{members} = " + call(
                "hep.histplot", Code(f"[h.values for h in {parts}]"), Code(f"{h}.edges"),
                ax=Code(self.ax[pad.id]), stack=True, histtype=layer.histtype, yerr=False,
                binwnorm=layer.binwnorm, **kwargs, linewidth=layer.linewidth,
                alpha=layer.alpha, zorder=layer.zorder, flow="none",
            ))
        return "\n".join(lines), members

    def layer_errorband(self, pad, layer: m.ErrorBandLayer):
        h = self.hvar[layer.of]
        binwnorm = getattr(self.spec.layer(layer.of), "binwnorm", None)
        lines = [f"# {layer.id}: uncertainty band on {layer.of}"]
        if not layer.visible:
            return lines[0], None
        lines += self._errors(layer.of, layer.content, "err_down", "err_up")
        if layer.relative:
            lines += [
                'with np.errstate(divide="ignore", invalid="ignore"):',
                f"    err_down, err_up = err_down / {h}.values, err_up / {h}.values",
            ]
            upper, lower = "np.nan_to_num(1 + err_up, nan=1.0)", "np.nan_to_num(1 - err_down, nan=1.0)"
        elif binwnorm is None:
            upper, lower = f"{h}.values + err_up", f"{h}.values - err_down"
        else:
            lines += [f"width = np.diff({h}.edges) / {lit(binwnorm)}",
                      f"band, err_down, err_up = {h}.values / width, err_down / width, err_up / width"]
            upper, lower = "band + err_up", "band - err_down"
        ax = self.ax[pad.id]
        if layer.style == "lines":
            for edge, label in ((upper, layer.label), (lower, None)):
                lines.append(call(
                    f"{ax}.stairs", Code(edge), Code(f"{h}.edges"), baseline=None,
                    color=layer.color, linewidth=layer.linewidth, linestyle=layer.linestyle,
                    label=label, alpha=layer.alpha, zorder=layer.zorder,
                ))
        else:
            lines.append(call(
                f"{ax}.stairs", Code(upper), Code(f"{h}.edges"), baseline=Code(lower), fill=True,
                facecolor=layer.facecolor, edgecolor=layer.color, linewidth=0, hatch=layer.hatch,
                label=layer.label, alpha=layer.alpha, zorder=layer.zorder,
            ))
        return "\n".join(lines), None

    def layer_graph(self, pad, layer: m.GraphLayer):
        self.helpers.add("load")
        g = ident(f"g_{layer.id}")
        self.refs(layer.ref)
        lines = [f"# {layer.id}: graph",
                 f"{g} = " + call("load", layer.ref.file, layer.ref.path, "graph")]
        if layer.visible:
            lines.append(call(
                f"{self.ax[pad.id]}.errorbar", Code(f'{g}["x"]'), Code(f'{g}["y"]'),
                xerr=Code(f'{g}["xerr"]') if layer.xerr else None,
                yerr=Code(f'{g}["yerr"]') if layer.yerr else None,
                label=layer.label, color=layer.color, marker=layer.marker,
                markersize=layer.markersize, linestyle=layer.linestyle,
                linewidth=layer.linewidth, capsize=layer.capsize, zorder=layer.zorder,
            ))
        return "\n".join(lines), None

    def layer_hist2d(self, pad, layer: m.Hist2DLayer):
        self.helpers.add("hist2d")
        ax = self.ax[pad.id]
        lines = [f"# {layer.id}: 2D histogram",
                 "xedges, yedges, values = " + call(
                     "hist2d", self.refs(layer.ref),
                     scale=layer.scale if layer.scale != 1.0 else None, cmin=layer.cmin)]
        if not layer.visible:
            return "\n".join(lines), None
        vmin, vmax = layer.zrange or (None, None)
        norm = Code(call("LogNorm" if layer.logz else "Normalize", vmin=vmin, vmax=vmax))
        lines += [
            "mesh = " + call(f"{ax}.pcolormesh", Code("xedges"), Code("yedges"), Code("values.T"),
                             norm=norm, cmap=layer.cmap, zorder=layer.zorder),
            f"{ax}.set_xlim(xedges[0], xedges[-1])",
            f"{ax}.set_ylim(yedges[0], yedges[-1])",
        ]
        if layer.bin_labels:
            lines += [
                "for i, x in enumerate((xedges[:-1] + xedges[1:]) / 2):",
                "    for j, y in enumerate((yedges[:-1] + yedges[1:]) / 2):",
                "        if np.isfinite(values[i, j]):",
                "            " + call(f"{ax}.text", Code("x"), Code("y"),
                                      Code(f"{lit(layer.bin_labels_format)}.format(values[i, j])"),
                                      ha="center", va="center", fontsize="x-small"),
            ]
        if layer.cbar:
            lines += [
                "# Like hep.hist2dplot: widen a single-axes figure so the main axes keep their size.",
                "cax = " + call("hep.append_axes", Code(ax), size="7%", pad=0.2,
                                extend=Code("len(fig.axes) == 1")),
                "cbar = fig.colorbar(mesh, cax=cax)",
            ]
            if layer.cbar_label:
                lines.append(call("cbar.set_label", layer.cbar_label))
        return "\n".join(lines), None

    def layer_ratio(self, pad, layer: m.RatioLayer):
        self.helpers.add("ratio")
        v = ident(layer.id)
        num, den = self.hvar[layer.num], self.hvar[layer.den]
        ax = self.ax[pad.id]
        lines = [f"# {layer.id}: ratio {layer.num} / {layer.den}",
                 f"{v}_values, {v}_err, {v}_den_err = ratio({num}, {den})"]
        if not layer.visible:
            return "\n".join(lines), None
        if layer.den_band:
            lo = hi = f"{v}_den_err"
            if _content_items(layer.den_band_content) != ["stat"]:
                lo, hi = f"{v}_band_down", f"{v}_band_up"
                lines += self._errors(layer.den, layer.den_band_content, lo, hi)
                lines += [
                    'with np.errstate(divide="ignore", invalid="ignore"):',
                    f"    {lo}, {hi} = {lo} / {den}.values, {hi} / {den}.values",
                ]
            lines.append(call(
                f"{ax}.stairs", Code(f"np.nan_to_num(1 + {hi}, nan=1.0)"), Code(f"{den}.edges"),
                baseline=Code(f"np.nan_to_num(1 - {lo}, nan=1.0)"), fill=True,
                facecolor="none", edgecolor=layer.den_band_color, linewidth=0,
                hatch=layer.den_band_hatch,
            ))
        errbar = layer.histtype == "errorbar"
        lines.append(call(
            "hep.histplot", Code(f"{v}_values"), Code(f"{num}.edges"), ax=Code(ax),
            yerr=Code(f"{v}_err"), histtype=layer.histtype, label=layer.label, color=layer.color,
            marker=layer.marker if errbar else None,
            markersize=layer.markersize if errbar else None,
            zorder=layer.zorder, flow="none",
        ))
        return "\n".join(lines), None

    def layer_pull(self, pad, layer: m.PullLayer):
        self.helpers.add("pull")
        num, den = self.hvar[layer.num], self.hvar[layer.den]
        lines = [f"# {layer.id}: pull ({layer.num} - {layer.den}) / sigma"]
        if layer.visible:
            lines.append(call(
                "hep.histplot", Code(f"pull({num}, {den})"), Code(f"{num}.edges"),
                ax=Code(self.ax[pad.id]), histtype="fill", yerr=False, color=layer.color,
                label=layer.label, zorder=layer.zorder, flow="none",
            ))
        return "\n".join(lines), None

    # -- annotations, axes, labels, legends

    def annotation(self, pad, ann) -> str:
        ax = self.ax[pad.id]
        if ann.kind == "text":
            return call(
                f"{ax}.text", *ann.xy, ann.text,
                transform=Code(f"{ax}.transAxes") if ann.coords == "axes" else None,
                ha=ann.ha, va=ann.va,
                rotation=ann.rotation or None,
                fontweight=None if ann.fontweight == "normal" else ann.fontweight,
                fontstyle=None if ann.fontstyle == "normal" else ann.fontstyle,
                fontsize=ann.fontsize, color=ann.color,
            )
        func = "axhline" if ann.kind == "hline" else "axvline"
        return call(f"{ax}.{func}", ann.at, color=ann.color, linestyle=ann.linestyle,
                    linewidth=ann.linewidth)

    def axes(self, pad: m.Pad) -> str:
        ax = self.ax[pad.id]
        xroot = _xroot(self.spec, pad)
        lines = []
        # Shared x axes take range and scale from the pad they share with.
        if xroot.xaxis.log:
            lines.append(f'{ax}.set_xscale("log")')
        if xroot.xaxis.range:
            lines.append(call(f"{ax}.set_xlim", *xroot.xaxis.range))
        if pad.yaxis.log:
            lines.append(f'{ax}.set_yscale("log")')
        if pad.yaxis.range:
            lines.append(call(f"{ax}.set_ylim", *pad.yaxis.range))
        for axis, name in ((pad.xaxis, "x"), (pad.yaxis, "y")):
            if axis.label is not None:
                lines.append(call(f"{ax}.set_{name}label", axis.label, loc=axis.label_loc))
                if axis.label_pos is not None:
                    lines.append(call(f"{ax}.{name}axis.set_label_coords", *axis.label_pos))
        if not pad.xaxis.ticklabels:
            lines.append(f'{ax}.tick_params(axis="x", labelbottom=False)')
        if not pad.yaxis.ticklabels:
            lines.append(f'{ax}.tick_params(axis="y", labelleft=False)')
        return "\n".join(lines)

    def label(self, pad: m.Pad) -> str:
        label, ax = pad.label, self.ax[pad.id]
        text = label.text
        if not label.data and text.startswith("Simulation"):
            # mplhep already prepends "Simulation" when data=False.
            text = text[len("Simulation"):].lstrip()
        lines = [
            f"plt.sca({ax})  # mplhep's label placement measures against the current axes",
            call(LABEL_FUNCS[label.experiment], ax=Code(ax), text=text, data=label.data,
                 lumi=label.lumi, com=label.com, year=label.year, loc=label.loc,
                 rlabel=label.rlabel, llabel=label.llabel, fontsize=label.fontsize),
        ]
        shifts = {}
        if label.offset:
            shifts.update(ExpLabel=label.offset, ExpText=label.offset)
        if label.lumi_offset:
            shifts["LumiText"] = label.lumi_offset
        if shifts:
            lines += [
                f"label_shift = {lit(shifts)}  # label moved by hand (axes fraction)",
                f"for t in {ax}.texts:",
                "    dx, dy = label_shift.get(type(t).__name__, (0, 0))",
                "    t.set_position((t.get_position()[0] + dx, t.get_position()[1] + dy))",
            ]
        return "\n".join(lines)

    def legend(self, pad: m.Pad) -> str:
        lg, ax = pad.legend, self.ax[pad.id]
        lines = [f"handles, labels = {ax}.get_legend_handles_labels()"]
        if lg.order or lg.reverse:
            self.helpers.add("sort_legend")
            lines.append("handles, labels = " + call(
                "sort_legend", Code("handles"), Code("labels"), order=lg.order,
                reverse=True if lg.reverse else None))
        lines += [
            "if handles:",
            "    " + call(
                f"{ax}.legend", Code("handles"), Code("labels"), loc=lg.loc,
                ncol=lg.ncol if lg.ncol != 1 else None,
                bbox_to_anchor=tuple(lg.bbox) if lg.bbox else None,
                borderaxespad=0 if lg.bbox else None,
                fontsize=lg.fontsize, frameon=lg.frameon, title=lg.title,
            ).replace("\n", "\n    "),
        ]
        return "\n".join(lines)


def _content_items(content) -> list[str]:
    """Band content as a list of items to add in quadrature."""
    if isinstance(content, list):
        return content
    return {"stat": ["stat"], "syst": ["syst"], "total": ["stat", "syst"]}[content]


def _ops_dict(ops: m.HistOps) -> dict:
    """Non-default hist1d options."""
    out = {}
    if ops.flow == "fold":
        out["flow"] = "fold"
    if ops.rebin is not None:
        out["rebin"] = ops.rebin
    if ops.xrange is not None:
        out["xrange"] = list(ops.xrange)
    if ops.scale != 1.0:
        out["scale"] = ops.scale
    if ops.normalize:
        out["normalize"] = True
    return out


def _syst_dict(syst) -> dict:
    return syst.model_dump(mode="json", exclude_defaults=True)


def _xroot(spec: m.PlotSpec, pad: m.Pad) -> m.Pad:
    """The pad whose x axis settings apply to ``pad`` (follows sharex chains)."""
    seen = set()
    while pad.sharex is not None and pad.id not in seen:
        seen.add(pad.id)
        pad = spec.pad(pad.sharex)
    return pad


def _span(start: int, n: int) -> str:
    return f"{start}" if n == 1 else f"{start}:{start + n}"


def _r(x: float) -> float:
    return round(x, 4)


def _indent(code: str, prefix: str = "    ") -> str:
    return "\n".join(prefix + line for line in code.splitlines())
